package com.runeclans.bot.events;

import com.runeclans.bot.events.BingoTilePool.Difficulty;
import com.runeclans.bot.events.BingoTilePool.Entry;
import net.dv8tion.jda.api.utils.data.DataArray;
import net.dv8tion.jda.api.utils.data.DataObject;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Ready-made sets of tiles a server can add to its pool, made from public RuneScape Wiki content the bot already carries ({@code catalog/bosses.json} and
 * {@code catalog/combat_achievements.json}, both generated by the wiki sync tools). Nothing is added until a server asks for a pack, and every tile can be
 * edited or removed afterwards. Real tile ideas from other clans are added by hand on the dashboard.
 */
public final class BingoStarterPacks {
    public static final String BOSS_DROPS = "boss-drops";
    public static final String COMBAT_ACHIEVEMENTS = "combat-achievements";

    public record Pack(String id, String title, String description) {}

    private static final Pattern FRACTION = Pattern.compile("^(\\d+)\\s*/\\s*(\\d+)$");
    /** Rarer than this is not a sensible bingo tile (a few thousand kills on average is already a lot). */
    private static final double RAREST = 1.0 / 20_000;
    private static final double COMMONEST = 1.0 / 50;

    private BingoStarterPacks() {}

    public static List<Pack> all() {
        return List.of(
                new Pack(BOSS_DROPS, "Boss drops", "\"Boss: item\" tiles for the rare drops on the wiki's boss pages. Rarer drops are harder and worth more."),
                new Pack(COMBAT_ACHIEVEMENTS, "Combat Mastery achievements", "One tile per combat achievement from the wiki, with its tier as the difficulty (up to 590 tiles: pick tiers to add)."));
    }

    /** The tiles of a pack, optionally only the given difficulties (none = all). Empty for an unknown pack. */
    public static List<Entry> tiles(String packId, Set<Difficulty> only) {
        List<Entry> all = switch (packId) {
            case BOSS_DROPS -> bossDrops(read("/catalog/bosses.json"));
            case COMBAT_ACHIEVEMENTS -> combatAchievements(read("/catalog/combat_achievements.json"));
            default -> List.of();
        };
        return only.isEmpty() ? all : all.stream().filter(e -> only.contains(e.difficulty())).toList();
    }

    /** "1/2000" or "6/128" as a chance, or empty for words like Always, Common or Varies. */
    static Optional<Double> chance(String rarity) {
        if (rarity == null) return Optional.empty();
        Matcher m = FRACTION.matcher(rarity.strip());
        if (!m.matches()) return Optional.empty();
        double denominator = Double.parseDouble(m.group(2));
        return denominator == 0 ? Optional.empty() : Optional.of(Double.parseDouble(m.group(1)) / denominator);
    }

    static Difficulty difficultyOf(double chance) {
        if (chance >= 1.0 / 150) return Difficulty.EASY;
        if (chance >= 1.0 / 600) return Difficulty.MEDIUM;
        if (chance >= 1.0 / 2500) return Difficulty.HARD;
        return Difficulty.ELITE;
    }

    static List<Entry> bossDrops(DataObject catalog) {
        List<Entry> tiles = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        DataArray bosses = catalog.getArray("bosses");
        for (int i = 0; i < bosses.length(); i++) {
            DataObject boss = bosses.getObject(i);
            String bossName = boss.getString("name", "");
            DataArray drops = boss.hasKey("drops") && !boss.isNull("drops") ? boss.getArray("drops") : DataArray.empty();
            for (int j = 0; j < drops.length(); j++) {
                DataObject drop = drops.getObject(j);
                Optional<Double> chance = chance(drop.getString("rarity", ""));
                if (chance.isEmpty() || chance.get() > COMMONEST || chance.get() < RAREST) continue;
                String label = BingoTilePool.cleanLabel(bossName + ": " + drop.getString("item", ""));
                if (label.length() > BingoTilePool.MAX_LABEL || label.endsWith(": ") || !seen.add(label.toLowerCase(Locale.ROOT))) continue;
                Difficulty difficulty = difficultyOf(chance.get());
                tiles.add(new Entry(label, difficulty.defaultPoints(), 1, difficulty, List.of("drop", slug(bossName)), true));
            }
        }
        return tiles;
    }

    static List<Entry> combatAchievements(DataObject catalog) {
        List<Entry> tiles = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        DataArray achievements = catalog.getArray("achievements");
        for (int i = 0; i < achievements.length(); i++) {
            DataObject a = achievements.getObject(i);
            Difficulty difficulty = Difficulty.parse(a.getString("tier", ""));
            if (difficulty == null) continue;
            String name = BingoTilePool.cleanLabel(a.getString("name", ""));
            String label = BingoTilePool.cleanLabel("Combat achievement: " + name);
            if (name.isEmpty() || label.length() > BingoTilePool.MAX_LABEL || !seen.add(label.toLowerCase(Locale.ROOT))) continue;
            List<String> tags = new ArrayList<>(List.of("combat achievement"));
            String boss = a.isNull("subcategory") ? "" : slug(a.getString("subcategory", ""));
            if (!boss.isEmpty() && boss.length() <= BingoTilePool.MAX_TAG) tags.add(boss);
            tiles.add(new Entry(label, difficulty.defaultPoints(), 1, difficulty, tags, true));
        }
        return tiles;
    }

    /** A boss or area name as a tag: lower case, letters and digits and single spaces. */
    static String slug(String name) {
        String s = name == null ? "" : name.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", " ").strip();
        return s.length() > BingoTilePool.MAX_TAG ? s.substring(0, BingoTilePool.MAX_TAG).strip() : s;
    }

    private static DataObject read(String resource) {
        try (InputStream in = BingoStarterPacks.class.getResourceAsStream(resource)) {
            if (in == null) return DataObject.empty().put("bosses", DataArray.empty()).put("achievements", DataArray.empty());
            return DataObject.fromJson(in);
        } catch (java.io.IOException | RuntimeException e) {
            return DataObject.empty().put("bosses", DataArray.empty()).put("achievements", DataArray.empty());
        }
    }
}
